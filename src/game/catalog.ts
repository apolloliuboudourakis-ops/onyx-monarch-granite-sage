export function damageOf(atk: number, mult: number, hp: number, max: number, dr: number): number {
  if (mult <= 0 || atk <= 0) return 0;
  const frac = 0.55 + 0.45 * (hp / Math.max(1, max));
  const raw = atk * mult * frac * (1 - Math.min(0.55, dr));
  return Math.max(1, Math.round(raw));
}

export function hitChance(opts: {
  kind: string;
  dist: number;
  minRange: number;
  maxRange: number;
  targetAir: boolean;
}): number {
  const acc = ACCURACY[opts.kind] ?? { near: 0.7, far: 0.4, role: "ground" as const };
  const span = Math.max(1, opts.maxRange - opts.minRange);
  const far = Math.min(1, Math.max(0, (opts.dist - opts.minRange) / span));
  let p = acc.near + (acc.far - acc.near) * far;
  if (opts.targetAir && acc.role === "ground") p *= 0.4;
  else if (opts.targetAir && acc.role === "sea") p *= 0.72;
  else if (!opts.targetAir && acc.role === "aa") p *= 0.5;
  return Math.round(Math.min(0.97, Math.max(0.12, p)) * 100) / 100;
}

export function hitBand(kind: string, minRange: number, maxRange: number): string {
  if (maxRange <= 0) return "—";
  const profile = ACCURACY[kind];
  const vsAir = profile?.role === "aa" || profile?.role === "air";
  const near = hitChance({ kind, dist: Math.max(1, minRange), minRange, maxRange, targetAir: vsAir });
  const far = hitChance({ kind, dist: maxRange, minRange, maxRange, targetAir: vsAir });
  const a = Math.round(Math.min(near, far) * 100);
  const b = Math.round(Math.max(near, far) * 100);
  return a === b ? `${a}%` : `${a}–${b}%`;
}


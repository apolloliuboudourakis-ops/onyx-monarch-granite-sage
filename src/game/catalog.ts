export interface Vs {
  light: number;
  armor: number;
  air: number;
  structure: number;
}

export interface UnitDef {
  id: UnitKind;
  name: string;
  cost: number;
  hp: number;
  move: number;
  minRange: number;
  maxRange: number;
  vision: number;
  atk: number;
  vs: Vs;
  armor: Armor;
  domain: "ground" | "air" | "sea";
  /** Ground: can ford water. Air: false means it cannot cross water. */
  water?: boolean;
  indirect: boolean;
  capture: boolean;
  repair: number;
  /** Shots per turn. Defaults to 1. */
  shots?: number;
  /** Manhattan blip radius. Weapons stay at 1. */
  radar?: number;
  /** Turns after you pay before it can act. */
  build?: number;
  /** Mines this unit carries. */
  mines?: number;
  blurb: string;
}


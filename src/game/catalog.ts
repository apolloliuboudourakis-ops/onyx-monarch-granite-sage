export function lineRoots(line: ResearchNode["line"]): ResearchNode[] {
  const nodes = RESEARCH.filter((node) => node.line === line);
  const ids = new Set(nodes.map((node) => node.id));
  return nodes.filter((node) => !node.after || !ids.has(node.after));
}

export function researchPaths(line: ResearchNode["line"]): BuyId[][] {
  const nodes = RESEARCH.filter((node) => node.line === line);
  const ids = new Set(nodes.map((node) => node.id));
  const kids = new Map<string, ResearchNode[]>();
  for (const node of nodes) {
    if (!node.after || !ids.has(node.after)) continue;
    const list = kids.get(node.after) ?? [];
    list.push(node);
    kids.set(node.after, list);
  }
  const paths: BuyId[][] = [];
  const walk = (node: ResearchNode, path: BuyId[]) => {
    const next = kids.get(node.id) ?? [];
    const here = [...path, node.id];
    if (next.length !== 1) {
      if (!next.length) paths.push(here);
      else for (const child of next) walk(child, here);
      return;
    }
    walk(next[0]!, here);
  };
  for (const root of lineRoots(line)) walk(root, root.after ? [root.after] : []);
  return paths;
}

export function ownedSet(unlocked: string | undefined): Set<string> {
  return new Set((unlocked ?? "").split(",").map((part) => part.trim()).filter(Boolean));
}

export function isDiscovered(unlocked: string | undefined, id: string): boolean {
  if ((FREE_BUY as string[]).includes(id)) return true;
  return ownedSet(unlocked).has(id);
}

export function researchReady(unlocked: string | undefined, id: string): ResearchNode | null {
  const node = RESEARCH.find((item) => item.id === id);
  if (!node || isDiscovered(unlocked, id)) return null;
  if (node.after && !isDiscovered(unlocked, node.after)) return null;
  return node;
}

